/* The three endpoints against real PostGIS, because everything that can go
 * quietly wrong here is a property of the database and not of the JavaScript:
 *
 *   The accent fold. `search_name` is generated by `place_searchable()` and
 *   the trigram index is on it. A query that folds any other way returns an
 *   empty list — not an error, an empty list — so "cafe zoom" finding
 *   "Café Zoöm" is the assertion that the index and the lookup agree, and it
 *   can only be made against the real function.
 *
 *   The redirects. A stop keeps a place id for the life of a trip and upstream
 *   reissues ids monthly. A merged place must still open by its old id, and a
 *   closed one must say it closed rather than 404 — two different answers a
 *   traveller can act on.
 *
 *   The widening. A sparse area must not return an empty list; the radius
 *   grows and the floor drops in the documented steps, and the response says
 *   which radius it ended up using.
 *
 * Its own database, named for this file rather than for the layer: this file
 * resets the schema, so does places-ingest.test.js, and the runner runs them
 * at the same time. Two files sharing one name here is three unrelated
 * assertions failing in whichever lost the race. See private-database.js.
 */

