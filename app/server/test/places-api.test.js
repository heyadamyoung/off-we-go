/* The bug that made the whole third tier dead on arrival, and that no test
   caught because every test either stubbed `placeSources` or ran with the
   fallback switched off.
 *
 * A degraded record's id is its upstream GERS id, not one of our uuids —
 * deliberately, so a stop can hold it and go on resolving once the cell
 * lands. The route then asked the database for those ids' sources, and
 * `place_id = any($1::uuid[])` raised 22P02 from inside the driver. Every
 * degraded answer was a 500: a traveller in a country nobody had ingested
 * got an error rather than a thinner list. */
test('a degraded record is served, not 500ed, though its id is not one of ours', {
  skip: reachable,
}, async t => {
  const bucket = {
    id: 'ov-degraded-1',
    gersId: 'ov-degraded-1',
    name: 'Somewhere Upstream Knows',
    lng: 139.7454,
    lat: 35.6586,
    category: 'museum',
    confidence: 0.9,
    metres: 10,
    sources: [{ source: 'overture', license: 'ODbL-1.0', upstreamId: 'osm:1', version: 'v' }],
  }
  /* The bucket is the only stub: what is being proved is what the route does
     with a record whose id is not a uuid, not how Parquet is read. */
  const { get } = await world(t, {
    placesFallback: {
      available: true,
      async readBounds() {
        return { places: [bucket], degraded: true, reason: null, cells: ['N35E139'] }
      },
      inFlight: () => 0,
    },
  })
  const response = await get('/api/places/nearby?lat=35.6586&lng=139.7454&radius=500&limit=5')
  assert.equal(response.statusCode, 200, response.body)
  const body = response.json()
  assert.equal(body.degraded, true)
  const found = body.places.find(place => place.id === 'ov-degraded-1')
  assert.ok(found, `the degraded record is missing from ${JSON.stringify(body.places)}`)
  /* And it carries its own licence through, which is the whole reason the
     record travels with its sources rather than being looked up. */
  assert.deepEqual(
    found.attribution.map(notice => notice.license),
    ['ODbL-1.0'],
  )
  assert.equal(response.headers['cache-control'], 'no-store')

  /* The same through search, which has its own call to the same helper. */
  const named = await get('/api/places/search?q=Somewhere&near=139.7454,35.6586')
  assert.equal(named.statusCode, 200, named.body)
  assert.equal(named.json().degraded, true)
})

/* The map's pin layer.
 *
 * What it replaced held the Netherlands and Scotland — the only two regions
 * the Wikipedia seeder was ever pointed at — and everywhere else the map asked
 * Wikipedia live from the phone. This answers anywhere from one indexed query,
 * and the ordering is the point: a viewport has no centre to measure from, so
 * the category weighting is the whole ranking and it has to put the museum
 * above the launderette. */
test('a viewport draws the best of what is in it, not the first rows found', {
  skip: reachable,
}, async t => {
  const { app } = await world(t)
  const box = 'west=4.87&south=52.35&east=4.89&north=52.37'
  const view = async query => {
    const reply = await app.inject({ method: 'GET', url: `/api/places/in-view?${query}` })
    assert.equal(reply.statusCode, 200, reply.body)
    return reply.json()
  }

  const all = await view(box)
  const names = all.places.map(place => place.name)
  assert.ok(names.includes('Van Gogh Museum'), names.join(', '))
  /* Below the confidence floor, so never drawn — the same floor every other
     query uses. */
  assert.ok(!names.includes('Rijksmuseum (dup)'), 'a 0.12-confidence duplicate is a pin')
  /* The museums and the gallery come before the laundry, whatever order the
     table happens to hold them in. */
  const museum = names.indexOf('Van Gogh Museum')
  const laundry = names.indexOf('Wasserette De Zeep')
  if (laundry >= 0) assert.ok(museum < laundry, `${names.join(' < ')}`)

  /* Zoomed out: only what is worth a dot from orbit. */
  const headline = await view(`${box}&headline=true`)
  assert.ok(headline.places.length > 0)
  assert.ok(headline.places.length < all.places.length, 'headline drew everything')
  for (const place of headline.places) assert.equal(place.big, true)
  assert.ok(
    !headline.places.some(place => place.category === 'services'),
    'a launderette survived a zoom out',
  )

  /* One attribution for the layer, which is how a map carries it, rather than
     a provenance trail per pin. */
  assert.ok(Array.isArray(all.attribution))
  for (const notice of all.attribution) assert.ok(notice.notice, JSON.stringify(notice))

  /* A pin is a dot and a label, plus the two numbers that decide how it is
     drawn. The rest of a place is one tap away, and sending it for three
     hundred pins is bytes nobody renders.
     `minzoom` and `rank` are here rather than one tap away because they are
     not about the place, they are about the drawing of it, and the map needs
     every pin's before it can draw any of them — see places/rank.js. */
  assert.deepEqual(Object.keys(all.places[0]).sort(), [
    'big',
    'category',
    'confidence',
    'id',
    'lat',
    'lng',
    'minzoom',
    'name',
    'rank',
  ])

  /* And they are numbers the map layer can actually use: a zoom inside the
     range the camera moves through, and a positive integer to sort by. */
  for (const place of all.places) {
    assert.ok(place.minzoom >= 11 && place.minzoom <= 18, `${place.name} draws at ${place.minzoom}`)
    assert.ok(Number.isInteger(place.rank) && place.rank > 0, `${place.name} ranks ${place.rank}`)
  }

  /* Public, like the layer it replaces: a map's pins are built from nobody's
     trip and carry nothing private. */
  const anonymous = await app.inject({ method: 'GET', url: `/api/places/in-view?${box}` })
  assert.equal(anonymous.statusCode, 200)

  /* And a box that is not a box is refused rather than guessed at. */
  const upsideDown = await app.inject({
    method: 'GET',
    url: '/api/places/in-view?west=4&south=53&east=5&north=52',
  })
  assert.equal(upsideDown.statusCode, 400)
})

/* The other question a map asks, and the reason it is a route of its own.
 *
 * The pins come from tiles. This is "is the ground under this view ingested
 * yet", and it used to be asked by requesting pins with `limit: 1` and
 * dropping them. When the cap on a viewport went — a zoom decides what is
 * drawn, and nothing truncates it — that became a request for every place in
 * the box: seventeen hundred rows and four seconds over Toronto, on every
 * settled pan, to read one boolean. */
/** `total;dur=3, data;dur=3, queue;dur=0` as three numbers. */
function whereTheTimeWent(reply) {
  const timing = reply.headers['server-timing'] || ''
  const parts = Object.fromEntries(
    timing.split(',').map(one => {
      const [name, value] = one.trim().split(';dur=')
      return [name, Number(value)]
    }),
  )
  for (const name of ['total', 'data', 'queue']) {
    assert.ok(Number.isFinite(parts[name]), `no ${name} in "${timing}"`)
  }
  /* The handler cannot take less time than the part of it that spoke to the
     database, which is the only relationship between them that always holds —
     and the one that makes `total` minus `data` mean anything. */
  assert.ok(parts.total >= parts.data, `total ${parts.total} < data ${parts.data}`)
  assert.ok(parts.queue >= 0, `queue ${parts.queue}`)
  return parts
}

test('every places route says where its milliseconds went', {
  skip: reachable,
}, async t => {
  /* A tile build is 1.3 milliseconds of database on an idle box, and the same
     build was measured at 270 to 970 in production while the planet was
     loading. Nothing about the query had changed. Without these three numbers
     there is no way to tell a slow query from a queue for a connection from a
     phone on a train, and the first two are ours to fix.
   *
   * On every route, not just the tiles. The tiles were the half reported as
   * slow, so the tiles were the half that got measured — and the result was a
   * layer where the one path anybody could see was the one already known to
   * be fast. A viewport took 3.7 seconds in production and nothing could say
   * whether that was the database, the process, the connection queue or
   * Toronto being far away. This test is what stops that happening again to
   * whichever route is added next. */
  const { app, get, ids } = await world(t)
  const box = 'west=4.87&south=52.35&east=4.89&north=52.37'
  const everywhere = [
    ['tile', () => app.inject({ method: 'GET', url: '/api/places/tiles/11/1051/673' })],
    ['coverage', () => app.inject({ method: 'GET', url: `/api/places/coverage?${box}` })],
    ['in-view', () => app.inject({ method: 'GET', url: `/api/places/in-view?${box}` })],
    ['search', () => get('/api/places/search?q=rijks')],
    ['nearby', () => get('/api/places/nearby?lat=52.36&lng=4.885')],
    ['one place', () => get(`/api/places/${ids.get('Rijksmuseum')}`)],
  ]
  for (const [name, ask] of everywhere) {
    const reply = await ask()
    assert.equal(reply.statusCode, 200, `${name}: ${reply.body}`)
    whereTheTimeWent(reply)
  }
})

