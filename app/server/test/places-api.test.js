test('a place that moved still resolves by its old id', { skip: reachable }, async t => {
  const { get, client, ids } = await world(t)
  const moved = '11111111-2222-4333-8444-555555555555'
  const alsoMoved = '11111111-2222-4333-8444-666666666666'
  /* Two dead ids pointing at one survivor, which is what a three-way merge
     leaves behind. Migration 043 makes `new_id` a foreign key into `places`,
     so a redirect can only ever point at a row that exists: a chain through a
     vanished intermediate is unrepresentable, and the hop limit in store.js is
     there against a bad ingest rather than against the normal case. */
  await client.query(
    `insert into place_redirects (old_id, new_id, reason) values ($1,$3,'merged'), ($2,$3,'merged')`,
    [moved, alsoMoved, ids.get('Rijksmuseum')],
  )
  for (const old of [moved, alsoMoved]) {
    const response = await get(`/api/places/${old}`)
    assert.equal(response.statusCode, 200)
    assert.equal(response.json().place.id, ids.get('Rijksmuseum'))
    assert.equal(response.json().redirectedFrom, old, 'and says which id it came in on')
    assert.ok(response.json().place.sources.length, 'the successor arrives whole')
  }
})

